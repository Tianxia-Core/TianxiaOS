fn blake2b_g(v: &mut [u64; 16], a: usize, b: usize, c: usize, d: usize, x: u64, y: u64) {
    v[a] = v[a].wrapping_add(v[b]).wrapping_add(x);
    v[d] = (v[d] ^ v[a]).rotate_right(32);
    v[c] = v[c].wrapping_add(v[d]);
    v[b] = (v[b] ^ v[c]).rotate_right(24);
    v[a] = v[a].wrapping_add(v[b]).wrapping_add(y);
    v[d] = (v[d] ^ v[a]).rotate_right(16);
    v[c] = v[c].wrapping_add(v[d]);
    v[b] = (v[b] ^ v[c]).rotate_right(63);
}

fn blake2b_compress(h: &mut [u64; 8], block: &[u8; 128], t_low: u64, t_high: u64, last: bool) {
    let mut m = [0u64; 16];
    for i in 0..16 {
        let mut word = [0u8; 8];
        word.copy_from_slice(&block[i * 8..(i + 1) * 8]);
        m[i] = u64::from_le_bytes(word);
    }
    let mut v = [0u64; 16];
    v[..8].copy_from_slice(h);
    v[8..16].copy_from_slice(&BLAKE2B_IV);
    v[12] ^= t_low;
    v[13] ^= t_high;
    if last {
        v[14] = !v[14];
    }
    for s in &BLAKE2B_SIGMA {
        blake2b_g(&mut v, 0, 4, 8, 12, m[s[0]], m[s[1]]);
        blake2b_g(&mut v, 1, 5, 9, 13, m[s[2]], m[s[3]]);
        blake2b_g(&mut v, 2, 6, 10, 14, m[s[4]], m[s[5]]);
        blake2b_g(&mut v, 3, 7, 11, 15, m[s[6]], m[s[7]]);
        blake2b_g(&mut v, 0, 5, 10, 15, m[s[8]], m[s[9]]);
        blake2b_g(&mut v, 1, 6, 11, 12, m[s[10]], m[s[11]]);
        blake2b_g(&mut v, 2, 7, 8, 13, m[s[12]], m[s[13]]);
        blake2b_g(&mut v, 3, 4, 9, 14, m[s[14]], m[s[15]]);
    }
    for i in 0..8 {
        h[i] ^= v[i] ^ v[i + 8];
    }
}

pub fn blake2b_256_personal(data: &[u8], personal: Option<&[u8]>) -> [u8; 32] {
    let mut h = BLAKE2B_IV;
    // Parameter block word 0: fanout=1, depth=1, digest_length=32 => 0x01010020
    h[0] ^= 0x01010000 ^ 32u64;
    if let Some(p) = personal {
        let mut p_buf = [0u8; 16];
        let copy_len = p.len().min(16);
        p_buf[..copy_len].copy_from_slice(&p[..copy_len]);
        let mut w6 = [0u8; 8];
        let mut w7 = [0u8; 8];
        w6.copy_from_slice(&p_buf[0..8]);
        w7.copy_from_slice(&p_buf[8..16]);
        h[6] ^= u64::from_le_bytes(w6);
        h[7] ^= u64::from_le_bytes(w7);
    }

    if data.is_empty() {
        let empty = [0u8; 128];
        blake2b_compress(&mut h, &empty, 0, 0, true);
    } else {
        let mut offset = 0usize;
        let mut total: u128 = 0;
        while data.len() - offset > 128 {
            let mut block = [0u8; 128];
            block.copy_from_slice(&data[offset..offset + 128]);
            total += 128;
            blake2b_compress(&mut h, &block, total as u64, (total >> 64) as u64, false);
            offset += 128;
        }
        let rem = data.len() - offset;
        let mut last_block = [0u8; 128];
        last_block[..rem].copy_from_slice(&data[offset..]);
        total += rem as u128;
        blake2b_compress(&mut h, &last_block, total as u64, (total >> 64) as u64, true);
    }

    let mut out = [0u8; 32];
    for i in 0..4 {
        out[i * 8..(i + 1) * 8].copy_from_slice(&h[i].to_le_bytes());
    }
    out
}

pub fn blake2b_256_hex(data: &[u8]) -> String {
    hex_encode(&blake2b_256_personal(data, None))
}

pub fn merkle_root_sha256(hashes: &[String]) -> String {
    if hashes.is_empty() {
        return sha256_hex(b"");
    }
    let mut layer: Vec<String> = hashes.to_vec();
    // Bounded tree reduction O(N)
    let mut guard = 0usize;
    while layer.len() > 1 && guard < 64 {
        let mut next = Vec::with_capacity((layer.len() + 1) / 2);
        let mut idx = 0usize;
        while idx < layer.len() {
            let left = &layer[idx];
            let right = if idx + 1 < layer.len() { &layer[idx + 1] } else { left };
            let combined = format!("{left}:{right}");
            next.push(sha256_hex(combined.as_bytes()));
            idx += 2;
        }
        layer = next;
        guard += 1;
    }
    layer.into_iter().next().unwrap_or_else(|| sha256_hex(b""))
}

pub fn derive_build_law_hmac_key() -> [u8; 32] {
    let seed = std::env::var("TIANXIA_SEAL_KEY")
        .unwrap_or_else(|_| "TIANXIAOS-SOVEREIGN-RATNA-SEAL-V4.2-ESTONIA".to_string());
    blake2b_256_personal(seed.as_bytes(), Some(b"TX_BLAW_SEAL"))
}

pub fn hex_encode(bytes: &[u8]) -> String {
    const HEX: &[u8; 16] = b"0123456789abcdef";
    let mut s = String::with_capacity(bytes.len() * 2);
    for &b in bytes {
        s.push(HEX[(b >> 4) as usize] as char);
        s.push(HEX[(b & 0x0f) as usize] as char);
    }
    s
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_sha256_vectors() {
        assert_eq!(
            sha256_hex(b""),
            "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855"
        );
        assert_eq!(
            sha256_hex(b"abc"),
            "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad"
        );
    }

    #[test]
    fn test_merkle_root_deterministic() {
        let leaves = vec![sha256_hex(b"a"), sha256_hex(b"b")];
        let root = merkle_root_sha256(&leaves);
        assert_eq!(root.len(), 64);
    }
}
